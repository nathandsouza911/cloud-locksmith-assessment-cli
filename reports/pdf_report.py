from __future__ import annotations
import pathlib
from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak,
)
from models.findings import FindingStatus
from models.assessment import AssessmentResult

_FOOTER = ("Generated locally. No data sent to Cloud Locksmith. "
           "Point-in-time assessment only — no changes were made to your tenant.")
POSTURE_DISCLAIMER = (
    "Identity Security Posture Score reflects only the Microsoft 365 identity/access controls "
    "this tool could evaluate. It is not a measure of overall cybersecurity maturity, breach "
    "likelihood, compliance, or insurance eligibility."
)

_DARK_BLUE = colors.HexColor("#1a3a5c")
_LIGHT_GRAY = colors.HexColor("#f5f5f5")
_GREEN = colors.HexColor("#2e7d32")
_AMBER = colors.HexColor("#f57f17")
_RED = colors.HexColor("#c62828")
_SKIP = colors.HexColor("#9e9e9e")

_STATUS_COLORS = {"PASS": _GREEN, "WARNING": _AMBER, "FAIL": _RED, "SKIPPED": _SKIP}
_GRADE_COLORS = {"Strong": _GREEN, "Good": _GREEN, "Fair": _AMBER, "Weak": _RED}
_SUCCESS = FindingStatus.SUCCESS


def write_pdf(result: AssessmentResult, output_path: pathlib.Path) -> None:
    doc = SimpleDocTemplate(
        str(output_path), pagesize=letter,
        rightMargin=0.75 * inch, leftMargin=0.75 * inch,
        topMargin=0.75 * inch, bottomMargin=0.75 * inch,
    )
    styles = getSampleStyleSheet()
    h1 = ParagraphStyle("H1", parent=styles["Heading1"], textColor=_DARK_BLUE, fontSize=20)
    h2 = ParagraphStyle("H2", parent=styles["Heading2"], textColor=_DARK_BLUE, fontSize=14)
    body = styles["Normal"]
    small = ParagraphStyle("small", parent=styles["Normal"], fontSize=8, textColor=colors.gray)
    brand = ParagraphStyle("brand", parent=styles["Normal"], fontSize=11, textColor=_DARK_BLUE)
    url_style = ParagraphStyle("url", parent=styles["Normal"], fontSize=9,
                               textColor=colors.HexColor("#1565c0"))
    story: list = []

    def footer() -> Paragraph:
        return Paragraph(_FOOTER, small)

    p = result.posture
    lw = result.license_waste

    # ── Page 1: Executive Summary ──────────────────────────────────────────
    story += [
        Paragraph("Cloud Locksmith", brand),
        Paragraph("Microsoft 365 Assessment Report", h1),
        Paragraph("Generated by Cloud Locksmith Assessment CLI", small),
        Paragraph("https://cloudlocksmith.co", url_style),
        Spacer(1, 0.2 * inch),
        Paragraph("Executive Summary", h2),
        Spacer(1, 0.1 * inch),
    ]
    grade_style = ParagraphStyle("grade", parent=styles["Normal"], fontSize=16,
                                 textColor=_GRADE_COLORS.get(p.grade, _DARK_BLUE))
    story.append(Paragraph(f"Identity Security Posture Score: <b>{p.grade.upper()}</b> "
                           f"({p.total_score}/{p.max_possible_score}, {p.score_pct:.0f}%)", grade_style))
    story.append(Spacer(1, 0.06 * inch))
    if p.grade_cap_reason:
        story += [Paragraph(f"Note: {p.grade_cap_reason}", small), Spacer(1, 0.06 * inch)]
    exec_rows = [["Area", "Result"]]
    exec_rows += [
        ["Global Admins", _fmt(result.global_admins.status, f"{result.global_admins.count} ({result.global_admins.risk_level})")],
        ["Privileged MFA", _fmt(result.privileged_mfa.status, f"{result.privileged_mfa.coverage_pct:.0f}%")],
        ["Tenant MFA", _fmt(result.tenant_mfa.status, f"{result.tenant_mfa.coverage_pct:.0f}%")],
        ["Security Defaults", _fmt(result.security_defaults.status, "Enabled" if result.security_defaults.enabled else "Disabled")],
        ["Guest Accounts", _fmt(result.guest_users.status, str(result.guest_users.total_count))],
        ["Potentially Reclaimable Seats", _fmt(lw.status, str(lw.unassigned_units))],
    ]
    story += [_tbl(exec_rows), Spacer(1, 0.2 * inch), footer(), PageBreak()]

    # ── Page 2: Identity Security Posture Score detail ─────────────────────
    story += [Paragraph("Identity Security Posture Score", h1), Spacer(1, 0.1 * inch)]
    evaluated = len(p.controls) - len(p.skipped_controls)
    story.append(Paragraph(
        f"<b>Grade: {p.grade}</b> — Score: {p.total_score}/{p.max_possible_score} "
        f"({p.score_pct:.0f}%) — {evaluated} of {len(p.controls)} controls evaluated", body))
    story.append(Spacer(1, 0.1 * inch))
    ctrl_rows = [["Control", "Status", "Pts", "Detail"]]
    for ctrl in p.controls:
        ctrl_rows.append([ctrl.name, ctrl.status, f"{ctrl.points}/{ctrl.max_points}", ctrl.detail])
    story.append(_tbl(ctrl_rows, status_col=1))
    if p.skipped_controls:
        story += [Spacer(1, 0.08 * inch), Paragraph(f"Skipped: {', '.join(p.skipped_controls)}", body)]
    story += [Spacer(1, 0.12 * inch), Paragraph(POSTURE_DISCLAIMER, small),
              Spacer(1, 0.2 * inch), footer(), PageBreak()]

    # ── Page 3: Identity, guests, policy ───────────────────────────────────
    story += [Paragraph("Identity, Access & Policy Findings", h1), Spacer(1, 0.1 * inch)]
    sec_rows = [["Finding", "Status", "Detail"]]
    sec_rows.append(["Global Administrators", result.global_admins.status.value,
                     _detail(result.global_admins, f"{result.global_admins.count} admins — {result.global_admins.risk_level} risk")])
    sec_rows.append(["Privileged MFA Coverage", result.privileged_mfa.status.value,
                     _detail(result.privileged_mfa, f"{result.privileged_mfa.coverage_pct:.0f}% ({result.privileged_mfa.mfa_registered_count}/{result.privileged_mfa.privileged_user_count})")])
    sec_rows.append(["Tenant MFA Coverage", result.tenant_mfa.status.value,
                     _detail(result.tenant_mfa, f"{result.tenant_mfa.coverage_pct:.0f}% ({result.tenant_mfa.mfa_registered_count}/{result.tenant_mfa.total_users})")])
    sec_rows.append(["Privileged Role Holders", result.privileged_roles.status.value,
                     _detail(result.privileged_roles, f"{result.privileged_roles.distinct_privileged_users} distinct users across {len(result.privileged_roles.roles)} roles")])
    sec_rows.append(["Guest Accounts", result.guest_users.status.value,
                     _detail(result.guest_users, f"{result.guest_users.total_count} guests")])
    sec_rows.append(["Stale Guests (90d+)", result.stale_guests.status.value,
                     _detail(result.stale_guests, f"{result.stale_guests.total_count} stale")])
    sec_rows.append(["Security Defaults", result.security_defaults.status.value,
                     _detail(result.security_defaults, "Enabled" if result.security_defaults.enabled else "Disabled")])
    sec_rows.append(["Conditional Access", result.conditional_access.status.value,
                     _detail(result.conditional_access, f"{result.conditional_access.enabled_count} enabled / {result.conditional_access.policy_count} total")])
    sec_rows.append(["User App Consent", result.user_consent.status.value,
                     _detail(result.user_consent, "Users can consent" if result.user_consent.users_can_consent else "Admin-restricted")])
    sec_rows.append(["Dormant Enabled Accounts (scored)", result.dormant_users.status.value,
                     _detail(result.dormant_users, f"{result.dormant_users.total_count} enabled, no sign-in 90d+")])
    sec_rows.append(["Disabled Still-Licensed (cost)", result.disabled_licensed_users.status.value,
                     _detail(result.disabled_licensed_users, f"{result.disabled_licensed_users.total_count} — reclaimable license")])
    story += [_tbl(sec_rows, status_col=1), Spacer(1, 0.2 * inch), footer(), PageBreak()]

    # ── Page 4: License optimization + metadata ────────────────────────────
    story += [Paragraph("License Optimization", h1), Spacer(1, 0.1 * inch)]
    if lw.status == _SUCCESS:
        rows = [
            ["Metric", "Value"],
            ["Active (paid) units", str(lw.active_units)],
            ["Consumed units", str(lw.consumed_units)],
            ["Potentially reclaimable seats", str(lw.unassigned_units)],
            ["Est. reclaimable spend (monthly)", f"${lw.estimated_reclaimable_monthly_usd:,.2f}"],
            ["Est. reclaimable spend (annual)", f"${lw.estimated_reclaimable_annual_usd:,.2f}"],
            ["Priced reclaimable seats", str(lw.priced_unassigned_units)],
            ["Unpriced reclaimable seats", str(lw.unpriced_unassigned_units)],
        ]
        story.append(_tbl(rows))
        story += [Spacer(1, 0.08 * inch),
                  Paragraph(f"Estimates from {lw.pricing_source}. Unassigned seats are potentially "
                            "reclaimable, not proven waste.", small)]
        if lw.partial_pricing_warning:
            story += [Spacer(1, 0.04 * inch), Paragraph(f"Note: {lw.partial_pricing_warning}", small)]
    else:
        story.append(Paragraph(f"License data unavailable: {lw.skipped_reason}", body))

    meta_rows = [
        ["Field", "Value"],
        ["Generated", result.generated_at],
        ["Schema Version", result.schema_version],
        ["Authentication", "Microsoft Device Code Flow"],
        ["Permissions", "Read-only delegated"],
        ["Data Handling", "No data transmitted to Cloud Locksmith."],
        ["Token Handling", "Tokens discarded after assessment."],
    ]
    story += [Spacer(1, 0.2 * inch), Paragraph("Assessment Metadata", h2),
              _tbl(meta_rows), Spacer(1, 0.2 * inch), footer()]

    doc.build(story)


def _fmt(status: FindingStatus, value: str) -> str:
    return value if status == _SUCCESS else status.value


def _detail(finding, success_detail: str) -> str:
    return success_detail if finding.status == _SUCCESS else (finding.skipped_reason or "")


def _tbl(data: list[list], status_col: int | None = None) -> Table:
    t = Table(data, hAlign="LEFT", repeatRows=1)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), _DARK_BLUE),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, _LIGHT_GRAY]),
        ("GRID", (0, 0), (-1, -1), 0.25, colors.lightgrey),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]
    if status_col is not None:
        for i, row in enumerate(data[1:], start=1):
            val = row[status_col] if status_col < len(row) else None
            col = _STATUS_COLORS.get(val, colors.black)
            style += [
                ("TEXTCOLOR", (status_col, i), (status_col, i), col),
                ("FONTNAME", (status_col, i), (status_col, i), "Helvetica-Bold"),
            ]
    t.setStyle(TableStyle(style))
    return t
